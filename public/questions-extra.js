  // دالة فحص والتحقق الصارم من بنية الأسئلة لتجنب أي انهيار
  function validateQuestion(q) {
    if (!q || typeof q !== 'object') return false;
    if (!q.id || !q.type || !q.category || !q.difficulty) return false;

    if (q.type === 'mcq') {
      if (!q.question || !Array.isArray(q.choices) || q.choices.length !== 4 || typeof q.correctIndex !== 'number') {
        return false;
      }
    } else if (q.type === 'tf') {
      if (!q.question || typeof q.answer !== 'boolean') return false;
    } else if (q.type === 'fill') {
      if (!q.text || !q.answer) return false;
    } else if (q.type === 'match') {
      if (!q.title || !Array.isArray(q.pairs) || q.pairs.length !== 4) return false;
      for (var i = 0; i < q.pairs.length; i++) {
        if (!q.pairs[i].right || !q.pairs[i].left) return false;
      }
    } else if (q.type === 'hints') {
      if (!Array.isArray(q.hints) || q.hints.length !== 5 || !q.answer) return false;
    } else if (q.type === 'direct') {
      if (!q.question || !q.answer) return false;
    } else {
      return false;
    }

    return true;
  }

